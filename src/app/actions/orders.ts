"use server";

import { revalidatePath } from "next/cache";
import { redirect } from "next/navigation";
import {
  describeProjectError,
  failedProjectBatch,
  runProjectBatch,
  unavailableProjectLabel,
  type ProjectBulkResult,
} from "../../domain/orders/bulk";
import { orderPriorities, orderStatuses, type OrderStatus } from "../../domain/orders/schema";
import { toClientSafeError } from "../../lib/errors/application-error";
import { getInternalContext } from "../../lib/supabase/next-server";

/*
 * Every mutation below follows the audited chain:
 *   UI -> server action -> OrderService -> OrderRepository -> app_* RPC -> Postgres -> activity event.
 * Nothing here writes to `orders` directly, and no identity, role, company or
 * assignee authorization is ever read from browser-supplied form data. The
 * actor is resolved server-side by getInternalContext().
 */

export type ProjectFormState = {
  error: string | null;
  fieldErrors: Record<string, string>;
};

function readText(formData: FormData, key: string): string {
  return String(formData.get(key) ?? "").trim();
}

function optionalText(formData: FormData, key: string): string | null {
  const value = readText(formData, key);
  return value || null;
}

/** HTML date inputs submit `YYYY-MM-DD`; the domain schema wants an ISO instant. */
function optionalDate(formData: FormData, key: string): string | null {
  const value = readText(formData, key);
  if (!value) return null;
  const parsed = new Date(`${value}T00:00:00`);
  if (Number.isNaN(parsed.getTime())) return null;
  return parsed.toISOString();
}

function isProjectStatus(value: string): value is OrderStatus {
  return (orderStatuses as readonly string[]).includes(value);
}

function formError(error: unknown, validationMessage: string): ProjectFormState {
  const safe = toClientSafeError(error);
  if (safe.code === "CONFLICT") {
    return {
      error: "This project was already submitted. Reload the page to see it.",
      fieldErrors: {},
    };
  }
  return { error: describeProjectError(error, validationMessage), fieldErrors: {} };
}

function readProjectFields(formData: FormData) {
  const priority = readText(formData, "priority");

  return {
    companyId: readText(formData, "company_id"),
    serviceId: readText(formData, "service_id"),
    title: readText(formData, "title"),
    priority: (orderPriorities as readonly string[]).includes(priority) ? priority : "normal",
    dueAt: optionalDate(formData, "due_at"),
    startedAt: optionalDate(formData, "started_at"),
    notes: optionalText(formData, "notes"),
    assigneeId: optionalText(formData, "assigned_to_profile_id"),
  };
}

export async function createProjectAction(
  _state: ProjectFormState,
  formData: FormData,
): Promise<ProjectFormState> {
  void _state;
  const fields = readProjectFields(formData);
  const requestId = readText(formData, "request_id");
  const fieldErrors: Record<string, string> = {};

  if (!fields.companyId) fieldErrors.company_id = "Choose a client.";
  if (!fields.serviceId) fieldErrors.service_id = "Choose a service.";
  if (!fields.title) fieldErrors.title = "Enter a project title.";
  if (Object.keys(fieldErrors).length > 0) {
    return { error: "Check the highlighted project details.", fieldErrors };
  }

  const context = await getInternalContext();
  let createdId: string;

  try {
    // The project number is generated by Postgres; it is never accepted here.
    // request_id makes a double submission idempotent inside app_create_order.
    const project = await context.services.orders.create(
      {
        request_id: requestId || undefined,
        company_id: fields.companyId,
        service_id: fields.serviceId,
        title: fields.title,
        priority: fields.priority,
        due_at: fields.dueAt,
        started_at: fields.startedAt,
        notes: fields.notes,
        assigned_to_profile_id: fields.assigneeId,
      },
      context.actor,
    );
    createdId = project.id;
  } catch (error) {
    return formError(error, "Check the project details and try again.");
  }

  revalidatePath("/orders");
  redirect(`/orders/${createdId}?created=1`);
}

export async function updateProjectAction(
  orderId: string,
  _state: ProjectFormState,
  formData: FormData,
): Promise<ProjectFormState> {
  void _state;
  const fields = readProjectFields(formData);

  if (!fields.title) {
    return { error: "Check the highlighted project details.", fieldErrors: { title: "Enter a project title." } };
  }
  if (!fields.serviceId) {
    return { error: "Check the highlighted project details.", fieldErrors: { service_id: "Choose a service." } };
  }

  const context = await getInternalContext();

  try {
    // company_id is intentionally absent: app_update_order rejects client
    // reassignment, and that rule is preserved rather than worked around.
    await context.services.orders.update(
      orderId,
      {
        service_id: fields.serviceId,
        title: fields.title,
        priority: fields.priority,
        due_at: fields.dueAt,
        started_at: fields.startedAt,
        notes: fields.notes,
      },
      context.actor,
    );
  } catch (error) {
    return formError(error, "Check the project details and try again.");
  }

  revalidatePath("/orders");
  revalidatePath(`/orders/${orderId}`);
  redirect(`/orders/${orderId}?saved=1`);
}

/** Server-resolved labels so an outcome never echoes browser-supplied text. */
async function resolveProjectLabels(orderIds: string[]): Promise<Map<string, string>> {
  const labels = new Map<string, string>();
  if (orderIds.length === 0) return labels;

  const context = await getInternalContext();
  try {
    for (const row of await context.services.orders.listLabels(orderIds)) {
      labels.set(row.id, `#${row.order_number} ${row.title}`);
    }
  } catch {
    // A label lookup failure must not mask the real mutation outcomes.
  }
  return labels;
}

async function runProjectAction(
  orderIds: string[],
  validationMessage: string,
  operation: (orderId: string) => Promise<unknown>,
): Promise<ProjectBulkResult> {
  const unique = Array.from(new Set(orderIds.filter(Boolean)));
  if (unique.length === 0) return { attempted: 0, succeeded: [], failed: [] };

  const labels = await resolveProjectLabels(unique);
  const result = await runProjectBatch(
    unique,
    (orderId) => labels.get(orderId) ?? unavailableProjectLabel,
    operation,
    validationMessage,
  );

  revalidatePath("/orders");
  for (const outcome of result.succeeded) revalidatePath(`/orders/${outcome.id}`);
  return result;
}

export async function bulkChangeProjectStatusAction(
  orderIds: string[],
  status: string,
): Promise<ProjectBulkResult> {
  if (!isProjectStatus(status)) {
    return failedProjectBatch(orderIds, "Choose a valid project status.");
  }

  const context = await getInternalContext();
  return runProjectAction(orderIds, "That status change was rejected.", (orderId) =>
    context.services.orders.changeStatus(orderId, { status }, context.actor),
  );
}

export async function bulkAssignProjectsAction(
  orderIds: string[],
  profileId: string | null,
): Promise<ProjectBulkResult> {
  const context = await getInternalContext();
  // The database rejects archived, non-existent and client-role assignees; the
  // action never pre-approves an assignee on the browser's word.
  return runProjectAction(orderIds, "That teammate cannot be assigned to this project.", (orderId) =>
    context.services.orders.assign(orderId, profileId, context.actor),
  );
}

export async function bulkArchiveProjectsAction(orderIds: string[]): Promise<ProjectBulkResult> {
  const context = await getInternalContext();
  // Archive only. There is no hard-delete path anywhere in the application.
  return runProjectAction(orderIds, "That project could not be archived.", (orderId) =>
    context.services.orders.archive(orderId, context.actor),
  );
}

export async function changeProjectStatusAction(
  orderId: string,
  status: string,
): Promise<ProjectBulkResult> {
  return bulkChangeProjectStatusAction([orderId], status);
}

export async function assignProjectAction(
  orderId: string,
  profileId: string | null,
): Promise<ProjectBulkResult> {
  return bulkAssignProjectsAction([orderId], profileId);
}

export async function archiveProjectAction(orderId: string): Promise<ProjectBulkResult> {
  return bulkArchiveProjectsAction([orderId]);
}
