import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { createClient } from "@supabase/supabase-js";
import type { Database } from "../src/lib/supabase/database.types";
import { assertLocalSupabaseUrl } from "../src/lib/env/public-env";

const execFileAsync = promisify(execFile);

const localAccounts = [
  {
    displayName: "Local Operator",
    email: "phase3a-owner@wolf-forge.local",
    password: "WolfForge-Local-3A!",
  },
  {
    displayName: "WF William",
    email: "wf-william@wolf-forge.local",
    // 123456 IS LOCAL DEVELOPMENT ONLY. Never reuse or export this credential.
    password: "123456",
  },
] as const;

function parseStatus(output: string) {
  return Object.fromEntries(
    output
      .split(/\r?\n/u)
      .map((line) => line.match(/^([A-Z_]+)="(.*)"$/u))
      .filter((match): match is RegExpMatchArray => Boolean(match))
      .map((match) => [match[1], match[2]]),
  );
}

async function main() {
  const projectRoot = resolve(import.meta.dirname, "..");
  const cli = resolve(projectRoot, "node_modules", ".bin", "supabase.cmd");
  const commandShell = process.env.ComSpec ?? "C:\\Windows\\System32\\cmd.exe";
  const { stdout } = await execFileAsync(commandShell, ["/d", "/s", "/c", `${cli} status --output env`], { cwd: projectRoot });
  const status = parseStatus(stdout);
  const apiUrl = status.API_URL;
  const publishableKey = status.PUBLISHABLE_KEY ?? status.ANON_KEY;
  const secretKey = status.SECRET_KEY ?? status.SERVICE_ROLE_KEY;
  if (!apiUrl || !publishableKey || !secretKey) throw new Error("Local Supabase status did not return the required keys.");
  assertLocalSupabaseUrl(apiUrl);

  const admin = createClient<Database>(apiUrl, secretKey, {
    auth: { persistSession: false, autoRefreshToken: false, detectSessionInUrl: false },
  });
  const { data: usersData, error: usersError } = await admin.auth.admin.listUsers({ page: 1, perPage: 1000 });
  if (usersError) throw usersError;
  const { data: ownerRole, error: roleError } = await admin.from("roles").select("id").eq("name", "owner").single();
  if (roleError || !ownerRole) throw roleError ?? new Error("Owner role is missing.");

  for (const account of localAccounts) {
    let user = usersData.users.find(
      (candidate) => candidate.email?.toLowerCase() === account.email,
    );

    if (user) {
      const { data, error } = await admin.auth.admin.updateUserById(user.id, {
        password: account.password,
        email_confirm: true,
      });
      if (error) throw error;
      user = data.user;
    } else {
      const { data, error } = await admin.auth.admin.createUser({
        email: account.email,
        password: account.password,
        email_confirm: true,
      });
      if (error || !data.user) throw error ?? new Error(`Local staff user ${account.email} was not created.`);
      user = data.user;
    }

    // private.handle_new_auth_user owns profile creation. The local setup role
    // intentionally has no direct profile INSERT privilege.
    const { data: profile, error: profileError } = await admin
      .from("profiles")
      .update({
        role_id: ownerRole.id,
        display_name: account.displayName,
        company_id: null,
        archived_at: null,
      })
      .eq("id", user.id)
      .select("id")
      .single();
    if (profileError || !profile) {
      throw profileError ?? new Error(`Local staff profile ${account.email} is missing.`);
    }
  }

  await writeFile(
    resolve(projectRoot, ".env.local"),
    `# Generated by npm run setup:frontend. Local public values only.\nSUPABASE_URL=${apiUrl}\nSUPABASE_PUBLISHABLE_KEY=${publishableKey}\n`,
    "utf8",
  );

  console.log("Phase 3A local frontend setup is ready.");
  for (const account of localAccounts) {
    console.log(`${account.displayName}: ${account.email}`);
  }
  console.log("WF William password 123456 is LOCAL DEVELOPMENT ONLY.");
  console.log("No service-role credential was written to .env.local.");
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
