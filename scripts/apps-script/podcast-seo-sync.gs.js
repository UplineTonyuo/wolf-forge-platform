/**
 * Podcast SEO change-notification webhook — Google Apps Script source.
 *
 * NOT installed automatically by anything in this repository. This file is
 * the deliverable; a human copies it into the Apps Script project bound to
 * the "PODCAST SEO Work Flow - WOLFFORGE" spreadsheet and wires up the
 * trigger by hand (steps below). It performs no Google Sheets writes and
 * requests no write scope — it only reads the active sheet's name and sends
 * one tiny "something changed" ping to Wolf Forge.
 *
 * WHAT IT SENDS (and nothing else):
 *   { eventType: "podcast_seo_changed", timestamp: <unix ms>, nonce: <string> }
 * signed with HMAC-SHA256 over that exact JSON string, in the
 * `X-Wolf-Forge-Signature` header, as lowercase hex.
 *
 * It NEVER sends client names, emails, credentials, login values, sheet row
 * contents, podcast URLs, notes, or any other workflow data — Google Sheets
 * stays the single source of truth, and this only tells Wolf Forge to go
 * re-read it.
 *
 * ---------------------------------------------------------------------
 * SETUP (do this by hand — nothing here runs itself)
 * ---------------------------------------------------------------------
 * 1. Open the "PODCAST SEO Work Flow - WOLFFORGE" spreadsheet.
 * 2. Extensions -> Apps Script. Paste this file's contents in as a new
 *    script file (e.g. `PodcastSeoSync.gs`).
 * 3. Project Settings (gear icon) -> Script Properties -> add:
 *      WOLF_FORGE_OPERATIONS_WEBHOOK_URL
 *        = https://<your-preview-or-production-domain>/api/operations/podcast-seo/sync
 *      WOLF_FORGE_OPERATIONS_WEBHOOK_SECRET
 *        = the SAME value as the Vercel env var OPERATIONS_SYNC_WEBHOOK_SECRET
 *      WOLF_FORGE_VERCEL_PROTECTION_BYPASS
 *        = REQUIRED for any Preview deployment. Every Preview on this Vercel
 *          project sits behind Vercel Authentication (Deployment Protection),
 *          which returns its own 401 "Protected deployment" challenge to ANY
 *          request with no Vercel session — including this one, since Apps
 *          Script is an external server with no Vercel login. That 401 is
 *          generated by Vercel's edge layer BEFORE the request ever reaches
 *          this app's code, which is why it never appears in this app's own
 *          logs and why `muteHttpExceptions` below made it invisible.
 *
 *          To fix: in the Vercel dashboard, Project Settings -> Deployment
 *          Protection -> enable "Protection Bypass for Automation". Vercel
 *          generates a secret there — put THAT value in this Script Property
 *          (it is unrelated to OPERATIONS_SYNC_WEBHOOK_SECRET; both are sent,
 *          for two different layers: Vercel's platform gate, then this app's
 *          own HMAC check). Not needed at all once this points at a
 *          Production deployment with Deployment Protection disabled/scoped
 *          differently.
 *    Do not put any of these values in the script source itself, and do not
 *    commit them anywhere.
 * 4. Run `createPodcastSeoOnEditTrigger` ONCE from the Apps Script editor
 *    (select it in the function dropdown, click Run). This is what makes it
 *    an INSTALLABLE trigger rather than a simple `onEdit(e)` function —
 *    simple triggers cannot make authenticated external requests
 *    (`UrlFetchApp` requires the `https://www.googleapis.com/auth/script.external_request`
 *    scope, which only an installable trigger can be granted), so a bare
 *    `onEdit(e)` in this file would silently fail to ever reach Wolf Forge.
 *    Authorize the requested scopes when prompted.
 * 5. Confirm the trigger exists: Apps Script editor -> Triggers (clock icon
 *    in the left sidebar) should show one entry calling `onPodcastSeoEdit`
 *    on "On edit" / "From spreadsheet" / "Installable".
 * 6. Edit a cell in a tab whose name starts with "PODCAST". A "Completed"
 *    entry in Apps Script's own Executions log does NOT prove the webhook
 *    was accepted — `muteHttpExceptions` means a rejected or protection-
 *    blocked call still "completes" successfully from Apps Script's point of
 *    view. Check Apps Script's Executions log entry for this run instead:
 *    it now prints exactly one sanitized line via `console.log` —
 *    `Podcast SEO webhook: stage=webhook_response status=<code> success=<true|false>`
 *    — and/or check Vercel's runtime logs for `integration.podcast_sync.accepted` /
 *    `.rejected`.
 *
 * To point this at a different deployment later (e.g. Preview -> Production),
 * change the WOLF_FORGE_OPERATIONS_WEBHOOK_URL script property, and update or
 * remove WOLF_FORGE_VERCEL_PROTECTION_BYPASS depending on whether the new
 * target has Deployment Protection enabled.
 */

/** Must match `PODCAST_SYNC_EVENT_TYPE` in `src/domain/operations/podcast-sync-webhook.ts`. */
var PODCAST_SYNC_EVENT_TYPE = "podcast_seo_changed";

/** Must match `PODCAST_TAB_TITLE_PREFIX` there too — only these tabs matter. */
var PODCAST_TAB_TITLE_PREFIX = "PODCAST";

/** Skip sending again if we already sent one within this many milliseconds — collapses a burst of rapid cell edits into one notification. */
var MIN_NOTIFY_INTERVAL_MS = 2000;

/**
 * Run this ONCE, by hand, from the Apps Script editor. Idempotent: safe to
 * run again later (it removes any existing trigger for this handler first)
 * if the trigger is ever accidentally deleted from the Triggers page.
 */
function createPodcastSeoOnEditTrigger() {
  var existing = ScriptApp.getProjectTriggers();
  for (var i = 0; i < existing.length; i++) {
    if (existing[i].getHandlerFunction() === "onPodcastSeoEdit") {
      ScriptApp.deleteTrigger(existing[i]);
    }
  }

  ScriptApp.newTrigger("onPodcastSeoEdit")
    .forSpreadsheet(SpreadsheetApp.getActiveSpreadsheet())
    .onEdit()
    .create();
}

/**
 * The installable onEdit handler. Fires for every edit to every tab in the
 * workbook — the tab-name check below is what keeps unrelated department
 * tabs from ever generating a webhook call.
 */
function onPodcastSeoEdit(e) {
  try {
    var sheet = e && e.range ? e.range.getSheet() : SpreadsheetApp.getActiveSheet();
    var sheetName = sheet ? sheet.getName() : "";
    if (sheetName.trim().toUpperCase().indexOf(PODCAST_TAB_TITLE_PREFIX) !== 0) {
      return;
    }

    if (!shouldNotifyNow_()) return;

    sendPodcastSeoChangeNotification_();
  } catch (error) {
    /*
     * An onEdit trigger that throws can be disabled by Google after enough
     * consecutive failures, which would silently kill realtime sync for
     * everyone. Swallow and let the NEXT edit try again rather than risk
     * that — Wolf Forge's own 5-minute fetch revalidation is the fallback
     * if every notification attempt fails.
     */
    Logger.log("onPodcastSeoEdit failed: " + (error && error.message ? error.message : error));
  }
}

/**
 * Self-debounce using CacheService, since Apps Script gives onEdit no
 * long-lived timer to coalesce rapid edits with — this is the Apps
 * Script-side half of "multiple rapid Sheet cell edits should collapse into
 * one refetch" (the server-side half is `shouldTriggerPodcastSyncEffect` in
 * `src/lib/security/podcast-sync-guard.ts`).
 */
function shouldNotifyNow_() {
  var cache = CacheService.getScriptCache();
  var key = "podcast_seo_last_notify_at";
  var last = cache.get(key);
  var now = Date.now();
  if (last && now - Number(last) < MIN_NOTIFY_INTERVAL_MS) {
    return false;
  }
  cache.put(key, String(now), 60);
  return true;
}

function sendPodcastSeoChangeNotification_() {
  var properties = PropertiesService.getScriptProperties();
  var url = properties.getProperty("WOLF_FORGE_OPERATIONS_WEBHOOK_URL");
  var secret = properties.getProperty("WOLF_FORGE_OPERATIONS_WEBHOOK_SECRET");
  /** Optional — required only while the target is a Vercel Preview deployment. See SETUP step 3 above. */
  var protectionBypass = properties.getProperty("WOLF_FORGE_VERCEL_PROTECTION_BYPASS");
  if (!url || !secret) {
    logWebhookOutcome_("config", null, false);
    return;
  }

  var payload = {
    eventType: PODCAST_SYNC_EVENT_TYPE,
    timestamp: Date.now(),
    nonce: Utilities.getUuid(),
  };
  var body = JSON.stringify(payload);
  var signatureBytes = Utilities.computeHmacSha256Signature(body, secret);
  var signatureHex = signatureBytes
    .map(function (byte) {
      var value = (byte + 256) % 256;
      var hex = value.toString(16);
      return hex.length === 1 ? "0" + hex : hex;
    })
    .join("");

  var headers = { "X-Wolf-Forge-Signature": signatureHex };
  if (protectionBypass) {
    headers["x-vercel-protection-bypass"] = protectionBypass;
  }

  /*
   * `muteHttpExceptions: true` on its own only stops UrlFetchApp from
   * THROWING on a non-2xx response — the response itself still has to be
   * captured and inspected, or a rejected (or, as diagnosed, a
   * platform-protection-blocked) call looks identical to success in Apps
   * Script's own Executions log.
   */
  var response = UrlFetchApp.fetch(url, {
    method: "post",
    contentType: "application/json",
    payload: body,
    headers: headers,
    muteHttpExceptions: true,
  });

  var status = response.getResponseCode();
  logWebhookOutcome_("webhook_response", status, status >= 200 && status < 300);
}

/**
 * The only diagnostic this script emits: which stage, the HTTP status (if
 * any), and a success boolean. Never the secret, the signature, the response
 * body, the spreadsheet id, or anything about the edited row.
 */
function logWebhookOutcome_(stage, status, success) {
  console.log(
    "Podcast SEO webhook: stage=" + stage + " status=" + (status === null ? "n/a" : status) + " success=" + success,
  );
}

/* Google Apps Script invokes these public entry points by stored function name. */
void createPodcastSeoOnEditTrigger;
void onPodcastSeoEdit;
