create table public.ticket_messages (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.tickets (id) on delete restrict,
  author_profile_id uuid references public.profiles (id) on delete restrict,
  author_type text not null,
  message_kind text not null,
  visibility text not null,
  body text not null,
  request_id uuid,
  created_at timestamptz not null default now(),
  constraint ticket_messages_author_type_valid check (author_type in ('internal', 'client', 'guest', 'system')),
  constraint ticket_messages_kind_valid check (message_kind in ('initial_request', 'reply', 'internal_note')),
  constraint ticket_messages_visibility_valid check (visibility in ('client', 'internal')),
  constraint ticket_messages_body_not_blank check (btrim(body) <> '' and char_length(body) <= 50000),
  constraint ticket_messages_internal_note_private check (
    (message_kind = 'internal_note') = (visibility = 'internal')
  ),
  constraint ticket_messages_author_consistent check (
    (author_type in ('internal', 'client') and author_profile_id is not null)
    or (author_type in ('guest', 'system') and author_profile_id is null)
