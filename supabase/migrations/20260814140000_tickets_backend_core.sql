create table public.tickets (
  id uuid primary key default gen_random_uuid(),
  ticket_number bigint generated by default as identity unique,
  public_ref text generated always as ('WF-TKT-' || lpad(ticket_number::text, 6, '0')) stored unique,
  company_id uuid references public.companies (id) on delete restrict,
  client_profile_id uuid references public.profiles (id) on delete restrict,
  requester_name text,
  requester_email text,
  subject text not null,
  status text not null default 'open',
  priority text not null default 'normal',
  assigned_to_profile_id uuid references public.profiles (id) on delete restrict,
  created_by_profile_id uuid references public.profiles (id) on delete restrict,
  source_form_submission_id uuid unique references public.form_submissions (id) on delete restrict,
  source_form_version_id uuid references public.form_versions (id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz,
  closed_at timestamptz,
  archived_at timestamptz,
  constraint tickets_subject_not_blank check (btrim(subject) <> '' and char_length(subject) <= 500),
  constraint tickets_requester_name_not_blank check (requester_name is null or btrim(requester_name) <> ''),
  constraint tickets_requester_email_not_blank check (requester_email is null or btrim(requester_email) <> ''),
  constraint tickets_status_valid check (status in (
    'open', 'in_progress', 'waiting_on_client', 'waiting_on_team', 'resolved', 'closed'
  )),
  constraint tickets_priority_valid check (priority in ('low', 'normal', 'high', 'urgent')),
  constraint tickets_client_requires_company check (client_profile_id is null or company_id is not null),
  constraint tickets_guest_requires_contact_form check (
    company_id is not null or source_form_submission_id is not null
  ),
  constraint tickets_form_source_consistent check (
    (source_form_submission_id is null and source_form_version_id is null)
    or (source_form_submission_id is not null and source_form_version_id is not null)
  ),
  constraint tickets_resolution_consistent check (
    (status = 'resolved' and resolved_at is not null and closed_at is null)
    or (status = 'closed' and closed_at is not null)
    or (status not in ('resolved', 'closed') and resolved_at is null and closed_at is null)
  )
);

