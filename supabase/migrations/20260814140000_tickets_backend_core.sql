-- Contact orchestration is the one permitted nested update to append-only Form
-- submission metadata. All answer rows and financial/contact history remain
-- immutable.
create or replace function private.prevent_form_history_mutation()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  -- Keep these record-field references inside the table branch: this trigger
  -- also protects value/file rows, whose records do not have orchestration
  -- columns.
  if tg_table_name = 'form_submissions' then
    if tg_op = 'UPDATE'
      and pg_trigger_depth() > 1
      and old.orchestration_type = 'contact_ticket'
      and old.orchestration_status = 'deferred'
      and new.orchestration_status = 'completed'
      and new.provenance ? 'ticket_id'
      and (to_jsonb(new) - array['orchestration_status', 'provenance'])
        = (to_jsonb(old) - array['orchestration_status', 'provenance'])
      and new.provenance = old.provenance || jsonb_build_object('ticket_id', new.provenance -> 'ticket_id')
    then
      return new;
    end if;
  end if;
  raise exception 'Form submission history is append-only' using errcode = '55000';
end;
$$;

