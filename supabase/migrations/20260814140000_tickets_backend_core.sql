create function private.current_ticket_actor()
returns table (profile_id uuid, role_name text, company_id uuid)
language sql
stable
security definer
set search_path = ''
as $$
  select profile_row.id, role_row.name, profile_row.company_id
  from public.profiles as profile_row
  join public.roles as role_row on role_row.id = profile_row.role_id
  where profile_row.id = (select auth.uid())
    and profile_row.archived_at is null;
$$;

create function private.can_access_ticket(p_ticket_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.tickets as ticket_row
    cross join private.current_ticket_actor() as actor
    where ticket_row.id = p_ticket_id
      and (
        (actor.role_name in ('owner', 'admin', 'manager', 'staff')
          and private.current_user_has_permission('tickets.view'))
        or (actor.role_name = 'client'
          and private.current_user_has_permission('tickets.view')
          and ticket_row.company_id = actor.company_id)
      )
  );
$$;

create function private.require_ticket_access(p_ticket_id uuid)
returns public.tickets
language plpgsql
security definer
set search_path = ''
as $$
declare
  ticket_row public.tickets;
begin
  if not private.can_access_ticket(p_ticket_id) then
    raise exception 'Ticket access is denied' using errcode = '42501';
  end if;
  select * into ticket_row from public.tickets where id = p_ticket_id;
  return ticket_row;
end;
$$;

