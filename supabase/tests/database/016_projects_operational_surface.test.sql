begin;

select plan(39);

-- -----------------------------------------------------------------------------
-- Fixtures
--
-- Every profile is created through the ordinary auth.users trigger so no test
-- shortcut bypasses the database-controlled role assignment.
-- -----------------------------------------------------------------------------

insert into auth.users (id, aud, role, email, created_at, updated_at)
values
  ('23000000-0000-0000-0000-000000000001', 'authenticated', 'authenticated', 'projects-owner@example.invalid', now(), now()),
  ('23000000-0000-0000-0000-000000000002', 'authenticated', 'authenticated', 'projects-staff@example.invalid', now(), now()),
  ('23000000-0000-0000-0000-000000000003', 'authenticated', 'authenticated', 'projects-archived@example.invalid', now(), now()),
  ('13000000-0000-0000-0000-000000000001', 'authenticated', 'authenticated', 'projects-client@example.invalid', now(), now());

update public.profiles
set role_id = (select id from public.roles where name = 'owner'), display_name = 'Projects Owner'
where id = '23000000-0000-0000-0000-000000000001';

update public.profiles
set role_id = (select id from public.roles where name = 'staff'), display_name = 'Projects Staff'
where id = '23000000-0000-0000-0000-000000000002';

update public.profiles
set role_id = (select id from public.roles where name = 'staff'), display_name = 'Archived Teammate'
where id = '23000000-0000-0000-0000-000000000003';

update public.profiles
set archived_at = now()
where id = '23000000-0000-0000-0000-000000000003';

-- The client profile deliberately keeps the default client role.

-- -----------------------------------------------------------------------------
-- Structural guarantees that do not depend on a session role
-- -----------------------------------------------------------------------------

select ok(
  not has_table_privilege('authenticated', 'public.orders', 'DELETE')
  and not has_table_privilege('authenticated', 'public.orders', 'INSERT')
  and not has_table_privilege('authenticated', 'public.orders', 'UPDATE'),
  'projects can only be written through the audited RPC boundary, never deleted'
);

select ok(
  not has_table_privilege('authenticated', 'public.order_tasks', 'DELETE'),
  'project tasks cannot be hard deleted by authenticated callers'
);

select ok(
  (
    select bool_and(prosecdef and proconfig @> array['search_path=""'])
    from pg_proc
    where pronamespace = 'public'::regnamespace
      and proname in (
        'app_create_order',
        'app_update_order',
        'app_change_order_status',
        'app_assign_order',
        'app_archive_order'
      )
  ),
  'every project mutation RPC is security definer with an empty search path'
);

select ok(
  not exists (
    select 1
    from pg_proc
    where pronamespace = 'public'::regnamespace
      and proname in (
        'app_create_order',
        'app_update_order',
        'app_change_order_status',
        'app_assign_order',
        'app_archive_order'
      )
      and proargnames && array['actor_id', 'actor_profile_id', 'p_actor_id', 'p_actor_profile_id']
  ),
  'no project mutation RPC accepts a caller-supplied actor identity'
);

create temporary table projects_fixture (
  company_id uuid,
  service_id uuid,
  order_a uuid,
  order_b uuid,
  order_c uuid,
  task_id uuid
) on commit drop;
insert into projects_fixture default values;
grant select, update on projects_fixture to authenticated;

-- -----------------------------------------------------------------------------
-- Owner session: full operational surface
-- -----------------------------------------------------------------------------

set local role authenticated;
set local "request.jwt.claim.role" = 'authenticated';
set local "request.jwt.claim.sub" = '23000000-0000-0000-0000-000000000001';

update projects_fixture
set company_id = (public.app_create_company('93000000-0000-0000-0000-000000000001', 'Projects Test Client')).id;

update projects_fixture
set service_id = (public.app_create_service(
  '93000000-0000-0000-0000-000000000002',
  '{"name":"Projects Test Service"}'::jsonb
)).id;

update projects_fixture
set order_a = (public.app_create_order(
  '93000000-0000-0000-0000-000000000003',
  (select company_id from projects_fixture),
  (select service_id from projects_fixture),
  'Attention Project'
)).id;

select isnt(
  (select order_number from public.orders where id = (select order_a from projects_fixture)),
  null,
  'the project number is generated by the database, never supplied by the caller'
);

select is(
  (
    select actor_profile_id
    from public.activity_events
    where entity_id = (select order_a from projects_fixture)
      and action = 'order.created'
  ),
  '23000000-0000-0000-0000-000000000001'::uuid,
  'the project create event derives its actor from auth.uid()'
);

-- Replaying the same request id must return the same project without a second
-- row and without a second activity event.
select is(
  (public.app_create_order(
    '93000000-0000-0000-0000-000000000003',
    (select company_id from projects_fixture),
    (select service_id from projects_fixture),
    'Attention Project'
  )).id,
  (select order_a from projects_fixture),
  'a replayed create request returns the original project'
);

select is(
  (
    select count(*)
    from public.activity_events
    where entity_id = (select order_a from projects_fixture)
      and action = 'order.created'
  ),
  1::bigint,
  'an idempotent create replay does not duplicate the activity event'
);

select is(
  (select count(*) from public.orders where title = 'Attention Project'),
  1::bigint,
  'an idempotent create replay does not duplicate the project'
);

-- Assignment rules
select throws_ok(
  $$select public.app_assign_order(
    (select order_a from projects_fixture),
    '23000000-0000-0000-0000-000000000009'
  )$$,
  '23514',
  'assignee must be an active internal profile',
  'a non-existent profile cannot be assigned to a project'
);

select throws_ok(
  $$select public.app_assign_order(
    (select order_a from projects_fixture),
    '13000000-0000-0000-0000-000000000001'
  )$$,
  '23514',
  'assignee must be an active internal profile',
  'a client profile can never be an operational project assignee'
);

select throws_ok(
  $$select public.app_assign_order(
    (select order_a from projects_fixture),
    '23000000-0000-0000-0000-000000000003'
  )$$,
  '23514',
  'assignee must be an active internal profile',
  'an archived internal profile cannot be assigned to a project'
);

select is(
  (public.app_assign_order(
    (select order_a from projects_fixture),
    '23000000-0000-0000-0000-000000000002'
  )).assigned_to_profile_id,
  '23000000-0000-0000-0000-000000000002'::uuid,
  'an active internal profile is accepted as a project assignee'
);

select is(
  (
    select count(*)
    from public.activity_events
    where entity_id = (select order_a from projects_fixture)
      and action = 'order.assigned'
  ),
  1::bigint,
  'assignment records exactly one activity event'
);

-- Status changes and the completion invariant
select is(
  (public.app_change_order_status((select order_a from projects_fixture), 'working')).status,
  'working',
  'an internal member can change a project status'
);

select ok(
  (
    select completed_at is null
    from public.orders
    where id = (select order_a from projects_fixture)
  ),
  'a non-complete project has no completion timestamp'
);

select ok(
  (public.app_change_order_status((select order_a from projects_fixture), 'complete')).completed_at is not null,
  'moving a project into Complete sets completed_at'
);

select ok(
  (public.app_change_order_status((select order_a from projects_fixture), 'working')).completed_at is null,
  'moving a project out of Complete clears completed_at'
);

select is(
  (
    select count(*)
    from public.activity_events
    where entity_id = (select order_a from projects_fixture)
      and action = 'order.status_changed'
  ),
  3::bigint,
  'every status change is audited'
);

-- The canonical patch surface must not accept a client reassignment.
select throws_ok(
  $$select public.app_update_order(
    (select order_a from projects_fixture),
    '{"company_id":"00000000-0000-0000-0000-000000000001"}'::jsonb
  )$$,
  '22023',
  'invalid project update patch',
  'a project cannot be moved to a different client through the update RPC'
);

-- -----------------------------------------------------------------------------
-- Attention rule: waiting_reply / pending_update / an overdue open task
-- -----------------------------------------------------------------------------

update projects_fixture
set order_b = (public.app_create_order(
  '93000000-0000-0000-0000-000000000004',
  (select company_id from projects_fixture),
  (select service_id from projects_fixture),
  'Quiet Project'
)).id;

update projects_fixture
set task_id = (public.app_create_task(
  '93000000-0000-0000-0000-000000000005',
  (select order_a from projects_fixture),
  'Overdue delivery task',
  null,
  null,
  now() - interval '2 days'
)).id;

select is(
  (
    select count(*)
    from public.orders as project
    where project.id in (select order_a from projects_fixture union all select order_b from projects_fixture)
      and project.archived_at is null
      and (
        project.status in ('waiting_reply', 'pending_update')
        or exists (
          select 1
          from public.order_tasks as task
          where task.order_id = project.id
            and task.archived_at is null
            and task.status not in ('complete', 'canceled')
            and task.due_at is not null
            and task.due_at < now()
        )
      )
  ),
  1::bigint,
  'an overdue open task alone puts a project into the attention set'
);

select is(
  (select public.app_change_order_status((select order_b from projects_fixture), 'waiting_reply')).status,
  'waiting_reply',
  'a project can be moved to Waiting on client'
);

select is(
  (
    select count(*)
    from public.orders as project
    where project.id in (select order_a from projects_fixture union all select order_b from projects_fixture)
      and project.archived_at is null
      and (
        project.status in ('waiting_reply', 'pending_update')
        or exists (
          select 1
          from public.order_tasks as task
          where task.order_id = project.id
            and task.archived_at is null
            and task.status not in ('complete', 'canceled')
            and task.due_at is not null
            and task.due_at < now()
        )
      )
  ),
  2::bigint,
  'a waiting-on-client project joins the attention set'
);

select is(
  (select public.app_change_task_status((select task_id from projects_fixture), 'complete')).status,
  'complete',
  'an overdue task can be completed'
);

select is(
  (
    select count(*)
    from public.orders as project
    where project.id in (select order_a from projects_fixture union all select order_b from projects_fixture)
      and project.archived_at is null
      and (
        project.status in ('waiting_reply', 'pending_update')
        or exists (
          select 1
          from public.order_tasks as task
          where task.order_id = project.id
            and task.archived_at is null
            and task.status not in ('complete', 'canceled')
            and task.due_at is not null
            and task.due_at < now()
        )
      )
  ),
  1::bigint,
  'completing the overdue task removes that project from the attention set'
);

-- -----------------------------------------------------------------------------
-- Archive is a soft, idempotent, audited operation
-- -----------------------------------------------------------------------------

update projects_fixture
set order_c = (public.app_create_order(
  '93000000-0000-0000-0000-000000000006',
  (select company_id from projects_fixture),
  (select service_id from projects_fixture),
  'Archivable Project'
)).id;

select ok(
  (public.app_archive_order((select order_c from projects_fixture))).archived_at is not null,
  'archiving a project stamps archived_at instead of deleting the row'
);

select ok(
  (public.app_archive_order((select order_c from projects_fixture))).archived_at is not null,
  'archiving an already archived project is idempotent'
);

select is(
  (
    select count(*)
    from public.activity_events
    where entity_id = (select order_c from projects_fixture)
      and action = 'order.archived'
  ),
  1::bigint,
  'an archive replay does not write a second activity event'
);

-- -----------------------------------------------------------------------------
-- Staff session: assignment scope, not client-private scope
-- -----------------------------------------------------------------------------

set local "request.jwt.claim.sub" = '23000000-0000-0000-0000-000000000002';

select is(
  (
    select count(*)
    from public.orders
    where id in (
      select order_a from projects_fixture
      union all select order_b from projects_fixture
      union all select order_c from projects_fixture
    )
  ),
  1::bigint,
  'a staff member without client-private read sees only their assigned project'
);

select throws_ok(
  $$select public.app_archive_order((select order_b from projects_fixture))$$,
  '42501',
  'project access is denied',
  'a staff member cannot archive a project outside their assignment scope'
);

select throws_ok(
  $$select public.app_create_order(
    '93000000-0000-0000-0000-000000000007',
    (select company_id from projects_fixture),
    (select service_id from projects_fixture),
    'Unauthorized Project'
  )$$,
  '42501',
  'permission denied: projects.create',
  'a staff member without projects.create cannot create a project'
);

-- -----------------------------------------------------------------------------
-- Client session: excluded from every internal project mutation
-- -----------------------------------------------------------------------------

set local "request.jwt.claim.sub" = '13000000-0000-0000-0000-000000000001';

select throws_ok(
  $$select public.app_create_order(
    '93000000-0000-0000-0000-000000000008',
    (select company_id from projects_fixture),
    (select service_id from projects_fixture),
    'Client Project'
  )$$,
  '42501',
  'verified internal authentication is required',
  'a client account cannot create projects'
);

select throws_ok(
  $$select public.app_change_order_status((select order_a from projects_fixture), 'complete')$$,
  '42501',
  'verified internal authentication is required',
  'a client account cannot change a project status'
);

select throws_ok(
  $$select public.app_assign_order(
    (select order_a from projects_fixture),
    '23000000-0000-0000-0000-000000000002'
  )$$,
  '42501',
  'verified internal authentication is required',
  'a client account cannot assign a project'
);

select throws_ok(
  $$select public.app_archive_order((select order_a from projects_fixture))$$,
  '42501',
  'verified internal authentication is required',
  'a client account cannot archive a project'
);

select is(
  (
    select count(*)
    from public.orders
    where id in (
      select order_a from projects_fixture
      union all select order_b from projects_fixture
      union all select order_c from projects_fixture
    )
  ),
  0::bigint,
  'a client account outside the owning company sees no projects'
);

-- -----------------------------------------------------------------------------
-- Storage-level proof that archiving never deletes
--
-- The scoped select policy hides archived projects from every authenticated
-- session, so the surviving row is verified outside RLS.
-- -----------------------------------------------------------------------------

reset role;

select is(
  (select count(*) from public.orders where id = (select order_c from projects_fixture)),
  1::bigint,
  'the archived project row still exists and was never hard deleted'
);

select ok(
  (select archived_at is not null from public.orders where id = (select order_c from projects_fixture)),
  'the archived project is retained with an archived_at stamp'
);

select is(
  (
    select count(*)
    from public.orders
    where id in (
      select order_a from projects_fixture
      union all select order_b from projects_fixture
      union all select order_c from projects_fixture
    )
  ),
  3::bigint,
  'all three fixture projects survive as rows regardless of session visibility'
);

select * from finish();
rollback;
